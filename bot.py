def رد_ديني(التعليق):
    تعليق = التعليق.strip().lower()

    if any(x in تعليق for x in ["السلام عليكم", "سلام عليكم"]):
        return "وعليكم السلام ورحمة الله وبركاته 🌷 حياك الله ونوّر الله قلبك 🤍"

    if any(x in تعليق for x in ["جزاك الله", "جزاك"]):
        return "وإياك يا رب 🤲 الله يجزاك خير ويكتب لنا ولك الأجر."

    if any(x in تعليق for x in ["الحمدلله", "الحمد لله"]):
        return "الحمد لله على كل حال 🤍 الله يديم علينا وعليك نعمه."

    if any(x in تعليق for x in ["استغفر", "استغفار"]):
        return "استغفر الله وأتوب إليه 🤲 الله يغفر لنا ولكم ويرحمنا برحمته."

    if any(x in تعليق for x in ["ما شاء الله", "ماشاء الله"]):
        return "ما شاء الله تبارك الرحمن 🤍 الله يبارك فيك ويحفظك."

    if "آمين" in تعليق:
        return "آمين يا رب العالمين 🤲 الله يكتب لك الخير وينور دربك."

    return "الله يسعدك ويكتب لك الخير والأجر 🤍 وذكّر نفسك دوم: إن ذكر الله تطمئن به القلوب."


if __name__ == "__main__":
    print(رد_ديني("جزاك الله خير"))
