def رد_ديني(التعليق):
    تعليق = التعليق.strip()

    # السلام والتحية
    if any(x in تعليق for x in ["السلام عليكم", "سلام عليكم", "السلام"]):
        return "وعليكم السلام ورحمة الله وبركاته 🌷 حياك الله يا غالي، الله يسعد قلبك ويكتب لك الخير 🤍"

    # الدعاء والشكر
    if any(x in تعليق for x in ["جزاك الله", "جزاكم الله", "الله يجزاك"]):
        return "وإياك يا رب 🤲 الله يجزاك خير ويكتب لنا ولك الأجر."

    # الحمد
    if any(x in تعليق for x in ["الحمدلله", "الحمد لله"]):
        return "الحمد لله دائمًا وأبدًا 🤍 الله يديم علينا وعليك نعمه."

    # الاستغفار
    if any(x in تعليق for x in ["استغفر", "استغفار", "أستغفر"]):
        return "أستغفر الله وأتوب إليه 🤲 الله يغفر لنا ولك ويرحمنا برحمته."

    # ما شاء الله
    if any(x in تعليق for x in ["ما شاء الله", "ماشاء الله"]):
        return "ما شاء الله تبارك الرحمن 🤍 الله يبارك فيك ويحفظك."

    # آمين
    if "آمين" in تعليق or "امين" in تعليق:
        return "آمين يا رب العالمين 🤲 الله يكتب لك الخير ويحقق لك ما تتمنى."

    # الدعاء
    if any(x in تعليق for x in ["ادعولي", "ادعوا لي", "دعواتكم", "دعوة"]):
        return "الله يفرّج همك وييسر أمرك ويرزقك من واسع فضله 🤲🤍"

    # الحزن والضيق
    if any(x in تعليق for x in ["حزين", "حزينة", "مهموم", "مهمومة", "ضايق", "ضايقة"]):
        return "الله يفرّج همك ويشرح صدرك 🤍 لا تيأس، إن مع العسر يسرًا."

    # طلب القرآن
    if any(x in تعليق for x in ["قرآن", "قران", "سورة", "آية", "ايه"]):
        return "الله يجعل القرآن نور صدرك وراحة لقلبك 🤍📖"

    # الصلاة
    if any(x in تعليق for x in ["صلوا", "الصلاة", "صلاة", "صل على النبي"]):
        return "اللهم صل وسلم وبارك على نبينا محمد ﷺ 🤍"

    # رد عام مناسب
    return "الله يسعدك ويكتب لك الخير والأجر 🤍 وذكّر نفسك دوم بذكر الله، فبذكر الله تطمئن القلوب 🌷"


if __name__ == "__main__":
    تعليقات = [
        "السلام عليكم",
        "جزاك الله خير",
        "ادعولي",
        "أنا مهموم",
        "ما شاء الله"
    ]

    for تعليق in تعليقات:
        print("التعليق:", تعليق)
        print("الرد:", رد_ديني(تعليق))
        print("-" * 30)
